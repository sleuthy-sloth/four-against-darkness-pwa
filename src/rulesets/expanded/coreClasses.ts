export const CORE_CLASS_IDS = CORE_CLASSES.map((c) => c.id)

export function parseClassDef(input: ClassDefInput): ClassDef {
  return ClassDef.parse(input)
}

export function classDefById(id: string): ClassDef | undefined {
  const input = CORE_CLASSES.find((c) => c.id === id)
  return input ? parseClassDef(input) : undefined
}
